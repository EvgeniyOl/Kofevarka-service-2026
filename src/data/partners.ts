/**
 * Правила блока партнёров.
 *
 * Живут отдельно от компонентов и стора: файл с компонентом должен
 * экспортировать только компоненты, иначе ломается горячая перезагрузка
 * (см. правило react-refresh в ESLint).
 */
import type { Partner } from '../api/client'

/** Данные партнёра без идентификатора — то, что вводит админ */
export type PartnerInput = Omit<Partner, 'id'>

/** Пустая карточка: с неё начинается добавление */
export const emptyPartner = (): PartnerInput => ({ name: '', note: '', logo: '' })

/**
 * Предел размера логотипа в байтах до кодирования.
 * Совпадает с проверкой на сервере (MAX_LOGO_LENGTH в api/_lib/types.ts):
 * в base64 картинка занимает примерно на треть больше.
 */
export const MAX_LOGO_BYTES = 400 * 1024

/** Ширина, до которой сжимаем загруженный логотип */
export const LOGO_MAX_WIDTH = 700
