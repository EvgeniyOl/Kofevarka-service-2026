/** Поле формы элемента: как подписать и что это за текст */
export interface ListField {
  field: string
  label: string
  hint?: string
  multiline?: boolean
  /** Поле хранит картинку: показываем превью и кнопку загрузки */
  image?: boolean
  max: number
}

export interface ListConfig {
  key: string
  /** Название списка: показывается в форме правки */
  name: string
  /** Где список видно на сайте */
  where: string
  /** Подпись кнопки добавления элемента */
  addLabel: string
  fields: ListField[]
  defaults: ItemValues[]
}

