/**
 * Правила карточек направлений ремонта.
 *
 * Живут отдельно от компонентов и стора, чтобы константы не смешивались
 * с разметкой: файл с компонентом должен экспортировать только компоненты,
 * иначе ломается горячая перезагрузка (см. правило react-refresh в ESLint).
 */
import type { Direction } from '../api/client'

/** Сколько карточек разрешено: то же число проверяет сервер */
export const MAX_DIRECTIONS = 6

/** Данные карточки без идентификатора — то, что вводит админ */
export type DirectionInput = Omit<Direction, 'id'>

/** Пустая карточка: с неё начинается добавление */
export const emptyDirection = (): DirectionInput => ({
  icon: '',
  title: '',
  text: '',
  points: [],
})
